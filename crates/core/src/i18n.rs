#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Lang {
    Id,
    En,
    Es,
    Vi,
}

impl Lang {
    pub fn parse(s: &str) -> Option<Lang> {
        match s.trim().to_lowercase().as_str() {
            "id" | "indonesia" | "indonesian" => Some(Lang::Id),
            "en" | "english" | "inggris" => Some(Lang::En),
            "es" | "espanol" | "español" | "spanish" => Some(Lang::Es),
            "vi" | "vn" | "viet" | "tieng viet" | "tiếng việt" | "vietnamese" => Some(Lang::Vi),
            _ => None,
        }
    }
    pub fn key(self) -> &'static str {
        match self {
            Lang::Id => "id",
            Lang::En => "en",
            Lang::Es => "es",
            Lang::Vi => "vi",
        }
    }
    pub const ALL: [Lang; 4] = [Lang::Id, Lang::En, Lang::Es, Lang::Vi];
}

