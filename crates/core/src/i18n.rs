pub fn menu_vi(english: &str) -> Option<&'static str> {
    let normalized = english.trim().replace("...", "…");
    if let Some((key, _)) = EN.iter().find(|(_, value)| value.eq_ignore_ascii_case(&normalized)) {
        if let Some((_, vietnamese)) = VI.iter().find(|(candidate, _)| candidate == key) {
            return Some(vietnamese);
        }
    }
    APP_MENU_VI.iter().find(|(key, _)| key.eq_ignore_ascii_case(&normalized)).map(|(_, vietnamese)| *vietnamese)
}

pub fn menu_es(english: &str) -> Option<&'static str> {
    let normalized = english.trim().replace("...", "…");
    if let Some((key, _)) = EN.iter().find(|(_, value)| value.eq_ignore_ascii_case(&normalized)) {
        if let Some((_, spanish)) = ES.iter().find(|(candidate, _)| candidate == key) {
            return Some(spanish);
        }
    }
    APP_MENU_ES.iter().find(|(key, _)| key.eq_ignore_ascii_case(&normalized)).map(|(_, spanish)| *spanish)
}

pub fn day_period(lang: Lang, hour: u32) -> &'static str {
    match (lang, hour < 12) {
        (Lang::Es, true) => "a. m.",
        (Lang::Es, false) => "p. m.",
        (Lang::Vi, true) => "SA",
        (Lang::Vi, false) => "CH",
        (_, true) => "AM",
        (_, false) => "PM",
    }
}

pub fn is_known(src: &str) -> bool {
    EN.iter().any(|(k, _)| *k == src)
}

pub fn tr(lang: Lang, src: &'static str) -> &'static str {
    match lang {
        Lang::Id => src,
        Lang::En => EN.iter().find(|(k, _)| *k == src).map(|(_, v)| *v).unwrap_or(src),
        Lang::Es => ES.iter().find(|(k, _)| *k == src).map(|(_, v)| *v).unwrap_or_else(|| tr(Lang::En, src)),
        Lang::Vi => VI.iter().find(|(k, _)| *k == src).map(|(_, v)| *v).unwrap_or_else(|| tr(Lang::En, src)),
    }
}

pub fn month_name(lang: Lang, m: u32, id: &'static str) -> &'static str {
    match lang {
        Lang::Id => id,
        Lang::En => {
            const N: [&str; 12] =
                ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"];
            N.get((m.max(1) - 1) as usize % 12).copied().unwrap_or(id)
        }
        Lang::Es => {
            const N: [&str; 12] = ["enero", "febrero", "marzo", "abril", "mayo", "junio", "julio", "agosto", "septiembre", "octubre", "noviembre", "diciembre"];
            N.get((m.max(1) - 1) as usize % 12).copied().unwrap_or(id)
        }
        Lang::Vi => {
            const N: [&str; 12] = ["Thg 1", "Thg 2", "Thg 3", "Thg 4", "Thg 5", "Thg 6", "Thg 7", "Thg 8", "Thg 9", "Thg 10", "Thg 11", "Thg 12"];
            N.get((m.max(1) - 1) as usize % 12).copied().unwrap_or(id)
        }
    }
}

pub fn weekday_labels(lang: Lang, monday_first: bool, id: [&'static str; 7]) -> [&'static str; 7] {
    match lang {
        Lang::Id => id,
        Lang::En => {
            if monday_first {
                ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]
            } else {
                ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"]
            }
        }
        Lang::Es => {
            if monday_first {
                ["lun", "mar", "mié", "jue", "vie", "sáb", "dom"]
            } else {
                ["dom", "lun", "mar", "mié", "jue", "vie", "sáb"]
            }
        }
        Lang::Vi => {
            if monday_first {
                ["T2", "T3", "T4", "T5", "T6", "T7", "CN"]
            } else {
                ["CN", "T2", "T3", "T4", "T5", "T6", "T7"]
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn indonesian_is_identity_and_english_translates() {
        assert_eq!(tr(Lang::Id, "Buka"), "Buka");
        assert_eq!(tr(Lang::En, "Buka"), "Open");
        assert_eq!(tr(Lang::En, "tidak ada"), "tidak ada");
    }

    #[test]
    fn spanish_translates_and_falls_back_to_english() {
        assert_eq!(tr(Lang::Es, "Pengaturan"), "Ajustes");
        assert_eq!(tr(Lang::Es, "Ukuran Visor"), "Tamaño del Visor");
        assert_eq!(tr(Lang::En, "Ukuran Visor"), "Visor size");
        assert_eq!(tr(Lang::Es, "tidak ada"), "tidak ada");
        for (k, v) in EN.iter() {
            let es = tr(Lang::Es, k);
            assert!(ES.iter().any(|(e, _)| e == k) || es == *v, "teks tanpa terjemahan Spanyol harus jatuh ke Inggris: {k}");
        }
    }

    #[test]
    fn vietnamese_translates_all_keys() {
        assert_eq!(Lang::parse("vi"), Some(Lang::Vi));
        assert_eq!(tr(Lang::Vi, "Pengaturan"), "Cài đặt");
        for (k, _) in EN.iter() {
            assert!(VI.iter().any(|(v, _)| v == k), "thiếu bản dịch Tiếng Việt cho: {k}");
        }
    }

    #[test]
    fn no_duplicate_keys() {
        for table in [EN, ES, VI] {
            for (i, (k, _)) in table.iter().enumerate() {
                assert!(!table[i + 1..].iter().any(|(k2, _)| k2 == k), "duplikat: {k}");
            }
        }
    }

    #[test]
    fn calendar_names() {
        assert_eq!(month_name(Lang::En, 11, "November"), "November");
        assert_eq!(month_name(Lang::En, 1, "Januari"), "January");
        assert_eq!(weekday_labels(Lang::En, true, ["Sen", "Sel", "Rab", "Kam", "Jum", "Sab", "Min"])[0], "Mon");
    }
}
